# PowerShell 7 の既定プロファイル。Linux/macOS の zsh 設定に近い操作感に揃える。
# 仕事用 PC だけの設定（PATH、curl の回避策、VM 用の関数など）は、
# 同じフォルダの profile.work.ps1 に書く。work を選んだ PC にだけ配られる。

$env:POWERSHELL_UPDATECHECK = 'Off'

# Colors
$PSStyle.FileInfo.Directory = "`e[38;2;137;180;250m"

# Aliases
# vi/vim -> nvim (nix の zsh.nix と揃える。PATH 上の Git 付属 vi より優先される)
Set-Alias -Name vi  -Value nvim
Set-Alias -Name vim -Value nvim
Set-Alias -Name lg  -Value lazygit
$env:EDITOR = 'nvim'

# -------------------------------
# PSReadLine / Completion
# -------------------------------

# 非対話のホスト（リダイレクト中など）では PSReadLine の設定が例外になるため、
# 対話コンソールのときだけ設定する。
$isInteractiveConsole = [Environment]::UserInteractive -and
    $Host.Name -eq 'ConsoleHost' -and
    -not [Console]::IsInputRedirected -and
    -not [Console]::IsOutputRedirected

if ($isInteractiveConsole -and (Get-Command Set-PSReadLineOption -ErrorAction SilentlyContinue)) {
    Import-Module PSReadLine -ErrorAction SilentlyContinue
    $setPsReadLineOption = Get-Command Set-PSReadLineOption -ErrorAction SilentlyContinue
    $setPsReadLineKeyHandler = Get-Command Set-PSReadLineKeyHandler -ErrorAction SilentlyContinue
    $validPsReadLineFunctions = @(
        $setPsReadLineKeyHandler.Parameters['Function'].Attributes |
            Where-Object { $_ -is [System.Management.Automation.ValidateSetAttribute] } |
            ForEach-Object { $_.ValidValues }
    )

    # PSReadLine のバージョンによって無い関数は、エラーにせず無視する。
    # Vi モードでは挿入モードとコマンドモードで別々に割り当てる必要がある。
    function Set-PSReadLineKeyHandlerSafe {
        param(
            [string] $Key,
            [string] $Function,
            [string[]] $ViMode = @('Insert', 'Command')
        )

        if ($validPsReadLineFunctions -contains $Function) {
            foreach ($mode in $ViMode) {
                Set-PSReadLineKeyHandler -Key $Key -Function $Function -ViMode $mode
            }
        }
    }

    # zsh の vi-mode と同じく、コマンドラインを vi キーで編集する。
    Set-PSReadLineOption -EditMode Vi
    Set-PSReadLineOption -HistorySearchCursorMovesToEnd

    Set-PSReadLineOption -Colors @{
        InlinePrediction = "`e[38;5;244m"
        ListPrediction = "`e[38;5;39m"
    }

    # Tab 補完は挿入モードだけ。↑↓は入力済みの文字列に前方一致する履歴だけを辿る
    # （zsh の history-prefix-up/down 相当）。
    Set-PSReadLineKeyHandlerSafe -Key Tab -Function MenuComplete -ViMode Insert
    Set-PSReadLineKeyHandlerSafe -Key UpArrow -Function HistorySearchBackward
    Set-PSReadLineKeyHandlerSafe -Key DownArrow -Function HistorySearchForward

    if ($setPsReadLineOption.Parameters.ContainsKey('PredictionSource')) {
        try {
            Set-PSReadLineOption -PredictionSource HistoryAndPlugin -ErrorAction Stop
        } catch {
            Set-PSReadLineOption -PredictionSource History -ErrorAction SilentlyContinue
        }
    }

    if ($setPsReadLineOption.Parameters.ContainsKey('PredictionViewStyle')) {
        Set-PSReadLineOption -PredictionViewStyle ListView -ErrorAction SilentlyContinue
    }

    if (Get-Module -ListAvailable -Name CompletionPredictor) {
        Import-Module CompletionPredictor -ErrorAction SilentlyContinue
    }

    if ((Get-Command fzf -ErrorAction SilentlyContinue) -and (Get-Module -ListAvailable -Name PSFzf)) {
        Import-Module PSFzf -ErrorAction SilentlyContinue

        if (Get-Command Set-PsFzfOption -ErrorAction SilentlyContinue) {
            Set-PsFzfOption `
                -PSReadlineChordProvider 'Ctrl+t' `
                -PSReadlineChordReverseHistory 'Ctrl+r' `
                -PSReadlineChordSetLocation 'Alt+c'
        }
    }
}

# 仕事用プロファイル。共通設定の後に読むので、ここで上書きできる。
$workProfile = Join-Path $PSScriptRoot 'profile.work.ps1'
if (Test-Path -LiteralPath $workProfile) { . $workProfile }
Remove-Variable workProfile -ErrorAction SilentlyContinue

# プロンプトは最後に差し替える。他の初期化がプロンプトを上書きしても starship を優先する。
if (Get-Command starship -ErrorAction SilentlyContinue) {
    Invoke-Expression (& starship init powershell)
}

# zoxide は prompt 関数を包んでディレクトリの移動を記録する。starship の prompt に
# 上書きされると記録されなくなるので、必ず starship の後に初期化する。
if (Get-Command zoxide -ErrorAction SilentlyContinue) {
    Invoke-Expression (& { (zoxide init powershell | Out-String) })
}

